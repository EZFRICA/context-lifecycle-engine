"""Raise sites the mutation sweep found unguarded, each pinned by what it refuses.

SCOPE: bucket 1 (embedder-agnostic). Every assertion is about WHICH input is
refused and HOW: an exit code, an exception type, a message. No vector space is
under test; where a command builds the stub embedder, it fails before embedding.

One test per SITE, not per exception class (cle-core-contracts, item 9). The CLI
tests assert the exception TYPE as well as the exit code, and that is the point
of them: remove a refusal and the command usually crashes a few lines further
down, also with exit code 1. A test that checked only the code would stay green
over a guard that no longer exists.
"""

from pathlib import Path

import pytest
import yaml
from typer.testing import CliRunner

from cle.cli.main import app
from cle.detect.embedders import UnknownCalibrationError, embedding_config_for, open_embedder
from cle.lifecycle.topology import render_diff
from cle.store.backends import InMemoryStore

ROOT = Path(__file__).resolve().parent.parent.parent
HISTORY = ROOT / "examples" / "prompt_history_adversarial.jsonl"


@pytest.fixture
def runner() -> CliRunner:
    return CliRunner()


@pytest.fixture
def spec(tmp_path) -> Path:
    """A spec written here, not read from `examples/`.

    The agent YAMLs there are gitignored and regenerated by `make_fixture.py`,
    so a clean clone has none. Every test using this one is refused before its
    centroid is compared to anything: a unit vector in the stub's 64 dimensions
    is enough, and nothing is embedded.
    """
    path = tmp_path / "status_report_agent.yaml"
    path.write_text(yaml.safe_dump({
        "name": "status_report",
        "detected_from": {"authored": "human"},
        "components": ["#blocks/recap_format", "#blocks/team_context"],
        "trigger": {"centroid": [1.0] + [0.0] * 63, "embedder_id": "stub:hashed64"},
    }, sort_keys=False))
    return path


def _said(result) -> str:
    text = result.output or ""
    try:
        text += result.stderr or ""
    except ValueError:  # a click that does not capture stderr separately
        pass
    return text


def _refused(result, code: int, message: str) -> None:
    """The command stopped ON PURPOSE, with this code, saying this."""
    assert result.exit_code == code, _said(result)
    assert isinstance(result.exception, SystemExit), (
        f"expected a deliberate exit, got {type(result.exception).__name__}: the "
        "refusal is gone and the command crashed further down instead"
    )
    assert message in _said(result), _said(result)


# --- global options: cle/cli/main.py, the app callback ----------------------

def test_an_unknown_store_backend_is_a_usage_error(runner, tmp_path, monkeypatch) -> None:
    monkeypatch.delenv("CLE_STORE", raising=False)
    result = runner.invoke(app, ["--store", "bogus", "ps", "--state-dir", str(tmp_path)])
    _refused(result, 2, "--store must be one of")


