# --- the embedding substrate --------------------------------------------------

def test_the_live_embedder_refuses_to_start_without_a_credential(monkeypatch) -> None:
    """Reached through `open_embedder`, never by importing the live class.

    No network: the constructor refuses before any client exists. Removing the
    refusal hands `None` to the SDK, which fails with an error that names neither
    of the two ways to fix it.
    """
    for name in ("CLE_VERTEX_PROJECT", "GEMINI_API_KEY", "GOOGLE_API_KEY"):
        monkeypatch.delenv(name, raising=False)
    with pytest.raises(RuntimeError, match="needs CLE_VERTEX_PROJECT"):
        open_embedder("real")


def test_a_topology_cannot_be_keyed_by_an_embedder_that_names_no_space() -> None:
    """The message is what bites: without this site, the next check still
    raises the same class, saying there is no calibration for `None`."""
    with pytest.raises(UnknownCalibrationError, match="exposes no embedder_id"):
        embedding_config_for(object())


